-- Ken Denmoku song master: Phase 0 schema, PostgreSQL 16+
-- Apply once with psql -v ON_ERROR_STOP=1 -f server/sql/001_init.sql
-- Public API must NOT expose Postgres directly to GitHub Pages.
BEGIN;
-- Deliberately omit pg_trgm indexes in the first deployment. Prefix indexes
-- are sufficient for v0; expensive substring indexes require a capacity review.

CREATE TABLE IF NOT EXISTS source_catalogs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code TEXT NOT NULL UNIQUE,
 display_name TEXT NOT NULL,
 source_url TEXT,
 license_id TEXT NOT NULL,
 license_url TEXT,
 attribution TEXT,
 last_import_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS artists (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL,
 name_key TEXT NOT NULL UNIQUE,
 identity_status TEXT NOT NULL DEFAULT 'provisional'
   CHECK (identity_status IN ('provisional','source_confirmed','human_confirmed')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (length(btrim(name)) BETWEEN 1 AND 200),
 CHECK (length(name_key) BETWEEN 1 AND 220)
);
CREATE INDEX IF NOT EXISTS artists_name_prefix ON artists (name_key text_pattern_ops);

CREATE TABLE IF NOT EXISTS songs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title TEXT NOT NULL,
 title_key TEXT NOT NULL,
 primary_artist_id BIGINT NOT NULL REFERENCES artists(id),
 -- A name+artist pair is a provisional song/work. Distinct recordings are separate below.
 identity_status TEXT NOT NULL DEFAULT 'provisional'
  CHECK (identity_status IN ('provisional','source_confirmed','human_confirmed')),
 release_year SMALLINT CHECK (release_year BETWEEN 1850 AND 2100),
 release_month SMALLINT CHECK (release_month BETWEEN 1 AND 12),
 release_day SMALLINT CHECK (release_day BETWEEN 1 AND 31),
 release_precision TEXT NOT NULL DEFAULT 'unknown'
  CHECK (release_precision IN ('unknown','year','month','day')),
 release_source_id BIGINT REFERENCES source_catalogs(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE (title_key, primary_artist_id),
 CHECK (length(btrim(title)) BETWEEN 1 AND 300),
 CHECK (length(title_key) BETWEEN 1 AND 330),
 CHECK (
  (release_precision='unknown' AND release_year IS NULL AND release_month IS NULL AND release_day IS NULL)
  OR (release_precision='year' AND release_year IS NOT NULL AND release_month IS NULL AND release_day IS NULL)
  OR (release_precision='month' AND release_year IS NOT NULL AND release_month IS NOT NULL AND release_day IS NULL)
  OR (release_precision='day' AND release_year IS NOT NULL AND release_month IS NOT NULL AND release_day IS NOT NULL)
 )
);
CREATE INDEX IF NOT EXISTS songs_title_prefix ON songs(title_key text_pattern_ops);
CREATE INDEX IF NOT EXISTS songs_primary_artist ON songs(primary_artist_id);

CREATE TABLE IF NOT EXISTS recordings (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 song_id BIGINT NOT NULL REFERENCES songs(id) ON DELETE CASCADE,
 musicbrainz_recording_id UUID UNIQUE,
 isrc TEXT,
 recording_type TEXT NOT NULL DEFAULT 'unknown'
  CHECK(recording_type IN('unknown','studio','live','cover','remix','remaster','alternate')),
 version_label TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS recordings_song_id ON recordings(song_id);

-- Four fields belong to EACH title and artist. Each value carries its own proof.
-- English denotes official English title/spelling, not auto-translation of Japanese.
-- Estimated values must never be treated as a source-confirmed pronunciation.
CREATE TABLE IF NOT EXISTS artist_names (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 artist_id BIGINT NOT NULL REFERENCES artists(id) ON DELETE CASCADE,
 kind TEXT NOT NULL CHECK(kind IN('hiragana','katakana','romaji','english','alternate')),
 value TEXT NOT NULL,
 search_key TEXT NOT NULL,
 verification TEXT NOT NULL DEFAULT 'estimated'
   CHECK(verification IN('estimated','source_confirmed','human_confirmed','derived_from_confirmed')),
 source_id BIGINT REFERENCES source_catalogs(id),
 source_url TEXT,
 checked_at TIMESTAMPTZ,
 reviewed_by TEXT,
 derived_from_id BIGINT REFERENCES artist_names(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(artist_id,kind,search_key),
 CHECK (length(btrim(value)) BETWEEN 1 AND 300),
 CHECK (verification='estimated' OR source_id IS NOT NULL OR reviewed_by IS NOT NULL OR derived_from_id IS NOT NULL),
 CHECK (verification <> 'derived_from_confirmed' OR derived_from_id IS NOT NULL),
 CHECK (kind <> 'english' OR verification IN ('source_confirmed','human_confirmed'))
);
CREATE INDEX IF NOT EXISTS artist_names_search_prefix ON artist_names(search_key text_pattern_ops);
CREATE INDEX IF NOT EXISTS artist_names_artist ON artist_names(artist_id);

CREATE TABLE IF NOT EXISTS song_names (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 song_id BIGINT NOT NULL REFERENCES songs(id) ON DELETE CASCADE,
 kind TEXT NOT NULL CHECK(kind IN('hiragana','katakana','romaji','english','alternate')),
 value TEXT NOT NULL,
 search_key TEXT NOT NULL,
 verification TEXT NOT NULL DEFAULT 'estimated'
   CHECK(verification IN('estimated','source_confirmed','human_confirmed','derived_from_confirmed')),
 source_id BIGINT REFERENCES source_catalogs(id),
 source_url TEXT,
 checked_at TIMESTAMPTZ,
 reviewed_by TEXT,
 derived_from_id BIGINT REFERENCES song_names(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(song_id,kind,search_key),
 CHECK (length(btrim(value)) BETWEEN 1 AND 300),
 CHECK (verification='estimated' OR source_id IS NOT NULL OR reviewed_by IS NOT NULL OR derived_from_id IS NOT NULL),
 CHECK (verification <> 'derived_from_confirmed' OR derived_from_id IS NOT NULL),
 CHECK (kind <> 'english' OR verification IN ('source_confirmed','human_confirmed'))
);
CREATE INDEX IF NOT EXISTS song_names_search_prefix ON song_names(search_key text_pattern_ops);
CREATE INDEX IF NOT EXISTS song_names_song ON song_names(song_id);

CREATE TABLE IF NOT EXISTS release_evidence (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 song_id BIGINT NOT NULL REFERENCES songs(id) ON DELETE CASCADE,
 source_id BIGINT NOT NULL REFERENCES source_catalogs(id),
 source_external_id TEXT,
 release_year SMALLINT CHECK(release_year BETWEEN 1850 AND 2100),
 release_month SMALLINT CHECK(release_month BETWEEN 1 AND 12),
 release_day SMALLINT CHECK(release_day BETWEEN 1 AND 31),
 precision TEXT NOT NULL CHECK(precision IN('year','month','day')),
 reference_url TEXT,
 observed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (
  (precision='year' AND release_year IS NOT NULL AND release_month IS NULL AND release_day IS NULL)
  OR (precision='month' AND release_year IS NOT NULL AND release_month IS NOT NULL AND release_day IS NULL)
  OR (precision='day' AND release_year IS NOT NULL AND release_month IS NOT NULL AND release_day IS NOT NULL)
 )
);
CREATE INDEX IF NOT EXISTS release_evidence_song ON release_evidence(song_id);

CREATE TABLE IF NOT EXISTS source_song_links (
 song_id BIGINT NOT NULL REFERENCES songs(id) ON DELETE CASCADE,
 source_id BIGINT NOT NULL REFERENCES source_catalogs(id),
 external_id TEXT NOT NULL,
 source_title TEXT,
 source_artist TEXT,
 observed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(source_id,external_id)
);
CREATE INDEX IF NOT EXISTS source_song_links_song ON source_song_links(song_id);

CREATE TABLE IF NOT EXISTS import_runs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_id BIGINT REFERENCES source_catalogs(id),
 status TEXT NOT NULL DEFAULT 'running'
   CHECK(status IN ('running','succeeded','failed')),
 scanned BIGINT NOT NULL DEFAULT 0,
 inserted BIGINT NOT NULL DEFAULT 0,
 updated BIGINT NOT NULL DEFAULT 0,
 rejected BIGINT NOT NULL DEFAULT 0,
 message TEXT,
 started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 finished_at TIMESTAMPTZ
);

-- Privileges are assigned outside this migration, after a read-only API role is
-- created by the VPS operator. Never place admin credentials in GitHub Pages.
COMMIT;
