-- 歌っちゃ王（YouTube @uta-cha-oh）専用データベース。
-- 既存の artists / songs とは別系統。1行 = YouTube動画1本。
-- アーティスト・楽曲それぞれに 名前 / ひらがな / カタカナ / 英語 を持つ。
-- 読みの verification:
--   estimated        … 自動推定（pykakasi）
--   main_db          … Kenのデンモク楽曲DB(artist_names/song_names)の値を流用
--   human_confirmed  … 人が確認・修正した値
BEGIN;
CREATE TABLE IF NOT EXISTS utachaoh_videos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  youtube_id TEXT NOT NULL UNIQUE CHECK (youtube_id ~ '^[A-Za-z0-9_-]{11}$'),
  video_title TEXT NOT NULL CHECK (length(btrim(video_title)) BETWEEN 1 AND 500),
  video_type TEXT NOT NULL DEFAULT '',
  artist_name TEXT NOT NULL DEFAULT '',
  artist_hiragana TEXT NOT NULL DEFAULT '',
  artist_katakana TEXT NOT NULL DEFAULT '',
  artist_english TEXT NOT NULL DEFAULT '',
  artist_reading_verification TEXT NOT NULL DEFAULT 'estimated'
    CHECK (artist_reading_verification IN ('estimated','main_db','human_confirmed')),
  song_title TEXT NOT NULL DEFAULT '',
  song_hiragana TEXT NOT NULL DEFAULT '',
  song_katakana TEXT NOT NULL DEFAULT '',
  song_english TEXT NOT NULL DEFAULT '',
  song_reading_verification TEXT NOT NULL DEFAULT 'estimated'
    CHECK (song_reading_verification IN ('estimated','main_db','human_confirmed')),
  -- 検索用（名前・ひらがな・カタカナ・英語を正規化して | で連結）
  artist_search_key TEXT NOT NULL DEFAULT '',
  song_search_key TEXT NOT NULL DEFAULT '',
  -- チャンネル内の並び（1 = 最新）
  channel_order INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS utachaoh_videos_order ON utachaoh_videos (channel_order);

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='kenapi') THEN
    GRANT SELECT ON utachaoh_videos TO kenapi;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='kenimport') THEN
    GRANT SELECT, INSERT, UPDATE, DELETE ON utachaoh_videos TO kenimport;
  END IF;
END $$;
COMMIT;
