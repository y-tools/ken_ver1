-- Ken's Denmoku V2: authenticated online user presence.
-- Apply after 202611110005_login_id.sql.
-- This is NOT an authentication registry: it records currently connected tabs.
-- Displayed users must have a valid Supabase user session.
create table if not exists public.online_sessions (
  user_id uuid not null references auth.users(id) on delete cascade,
  tab_id uuid not null,
  connected_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  primary key (user_id, tab_id)
);
create index if not exists online_sessions_seen_at_idx
  on public.online_sessions(last_seen_at);
alter table public.online_sessions enable row level security;
revoke all on public.online_sessions from public, anon, authenticated;

-- Realtime subscribes only as an admin/owner; listeners cannot read anybody's
-- identity, device IDs, or presence state via a direct table query.
grant select on public.online_sessions to authenticated;
drop policy if exists "Admins can view online sessions" on public.online_sessions;
create policy "Admins can view online sessions" on public.online_sessions
  for select to authenticated
  using ((select private.current_role()) in ('admin','owner'));

create or replace function public.presence_heartbeat(p_tab_id uuid)
returns void language plpgsql security definer set search_path='' as $$
declare
  uid uuid := (select auth.uid());
begin
  if uid is null then
    raise exception 'Authentication required' using errcode='28000';
  end if;
  if p_tab_id is null then
    raise exception 'Tab ID required' using errcode='22023';
  end if;
  -- Prevent unbounded active sessions being generated by a single account.
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext(uid::text)::bigint);
  delete from public.online_sessions
    where user_id=uid and last_seen_at < now()-interval '1 day';
  if not exists(select 1 from public.online_sessions where user_id=uid and tab_id=p_tab_id)
    and (select count(*) from public.online_sessions
         where user_id=uid and last_seen_at>now()-interval '75 seconds')>=12 then
    raise exception 'Too many active sessions' using errcode='53300';
  end if;
  insert into public.online_sessions(user_id,tab_id,last_seen_at)
    values(uid,p_tab_id,now())
    on conflict(user_id,tab_id) do update
    set last_seen_at=now();
end;
$$;
revoke all on function public.presence_heartbeat(uuid) from public,anon;
grant execute on function public.presence_heartbeat(uuid) to authenticated;

create or replace function public.presence_leave(p_tab_id uuid)
returns void language plpgsql security definer set search_path='' as $$
declare uid uuid := (select auth.uid());
begin
  if uid is null then return; end if;
  if p_tab_id is null then return; end if;
  delete from public.online_sessions
    where user_id=uid and tab_id=p_tab_id;
end;
$$;
revoke all on function public.presence_leave(uuid) from public,anon;
grant execute on function public.presence_leave(uuid) to authenticated;

-- Return one row per authenticated online user. User-controlled nicknames
-- never become authoritative identities: role and display name come from
-- authenticated profiles. No emails are exposed to browser clients.
create or replace function public.presence_admin_list()
returns jsonb language plpgsql stable security definer set search_path='' as $$
declare
  uid uuid := (select auth.uid());
  role_name text;
  result jsonb;
begin
  if uid is null then
    raise exception 'Authentication required' using errcode='28000';
  end if;
  select p.role into role_name from public.profiles p where p.id=uid;
  if role_name is distinct from 'admin' and role_name is distinct from 'owner' then
    raise exception 'Admin permission required' using errcode='42501';
  end if;
  select coalesce(pg_catalog.jsonb_agg(
    pg_catalog.jsonb_build_object(
      'userId',p.id,
      'displayName',p.display_name,
      'loginId',p.login_id,
      'role',p.role,
      'connections',a.connection_count,
      'lastSeenAt',floor(extract(epoch from a.latest_seen)*1000)::bigint
    )
    order by case p.role when 'owner' then 0 when 'admin' then 1 else 2 end,
      p.display_name,p.id
  ),'[]'::jsonb) into result
  from (
    select user_id,count(*)::integer as connection_count,max(last_seen_at) as latest_seen
    from public.online_sessions
    where last_seen_at > now()-interval '75 seconds'
    group by user_id
  ) a join public.profiles p on p.id=a.user_id;
  return result;
end;
$$;
revoke all on function public.presence_admin_list() from public,anon;
grant execute on function public.presence_admin_list() to authenticated;

